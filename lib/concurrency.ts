// Map over items running at most `limit` async tasks at once. Preserves input order.
// Use to cap fan-out of external calls (e.g. geocoding) so we don't burst-ban
// rate-limited providers or exhaust sockets on a cold fetch.
export async function mapWithConcurrency<T, R>(
  items: readonly T[],
  limit: number,
  fn: (item: T, index: number) => Promise<R>,
): Promise<R[]> {
  if (items.length === 0) return []
  const results = new Array<R>(items.length)
  let next = 0
  const workers = Array.from({ length: Math.min(limit, items.length) }, async () => {
    while (next < items.length) {
      const i = next++
      results[i] = await fn(items[i], i)
    }
  })
  await Promise.all(workers)
  return results
}
